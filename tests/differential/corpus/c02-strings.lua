-- c02: string library — basic ops, patterns, format (diff vs native z8lua)

-- basic
print(string.len("hello"), #("hello"))
print(string.sub("hello", 2, 4), string.sub("hello", 2), string.sub("hello", 1, -2))
print(string.sub("hello", 4, 2), string.sub("hello", 10, 20), string.sub("hello", -100, 100))
print(string.sub("hello", 0, 3), string.sub("hello", -1), string.sub("hello", 6))
print(string.reverse("abc"), string.reverse(""), string.reverse("a b"))
print(string.lower("AbC123"), string.upper("aBc123"), string.lower(""), string.upper(""))
print(string.rep("ab", 3), string.rep("ab", 3, "-"), string.rep("x", 0), string.rep("", 5))
print(string.rep("ab", 1))

-- byte / char
print(string.byte("ABC"), string.byte("ABC", 2), string.byte("ABC", -1))
print(string.byte("ABC", 2, 3), string.byte("ABC", 5), string.byte("ABC", 0))
print(string.char(65, 66, 67), string.char(), string.char(0), #string.char(0, 1, 2))
print(pcall(string.char, 300))
print(pcall(string.char, -1))
print(string.byte("\0\1\255", 1, 3))

-- find (plain + pattern)
print(string.find("hello world", "wor"))
print(string.find("hello world", "wor", 1, true))
print(string.find("hello", "xyz"))
print(string.find("hello", "^he"))
print(string.find("hello", "l+"))
print(string.find("hello", "l+"), string.find("hello world", "%s"))
print(string.find("aXbXc", "X", 2))
print(string.find("aXbXc", "X", 5))
print(string.find("aXbXc", "X", 6))
print(string.find("abc", "a.c"))
print(string.find("abc", "a.c", 2))
print(string.find("hello", "l", 1, false))
print(string.find("abc", "[b-d]"))
print(string.find("abc", "[^a]"))
print(string.find("a1b2", "%a%d"))
print(string.find("hello", "%a"), string.find("123", "%a"))
print(string.find("  x", "^%s"))
print(string.find("abc", "$"))
print(string.find("abc", "c$"))
print(string.find("abc", "b"), string.find("abc", "bb"))
print(string.find("a\nb", "a.b"))
print(pcall(string.find, "abc", "%"))
print(pcall(string.find, "abc", "["))
print(string.find("(x)", "%b()"))
print(string.find("(x", "%b()"))
print(string.find("hello", "l%f[%w]"))
print(string.find("hello", "l%f[%W]"))

-- match
print(string.match("hello world", "(%w+) (%w+)"))
print(string.match("key=value", "(%w+)=(%w+)"))
print(string.match("2026-10-21", "(%d+)-(%d+)-(%d+)"))
print(string.match("abc", "^a"))
print(string.match("abc", "b"))
print(string.match("no digits", "%d"))
print(string.match("a1b2c3", "%a%d"))
print(string.match("xy", "(.)"))
print(string.match("xy", "(..)"))
print(string.match("test", "()b()"))
print(string.match("aXb", "(X)"))
print(pcall(string.match, "abc", "%1"))
print(pcall(string.match, "abc", "("))

-- gsub (string / function / table replacements)
print(string.gsub("hello", "l", "L"))
print((string.gsub("hello", "l", "L")))
print((string.gsub("hello world", "%w+", "<%0>")))
print((string.gsub("abc", "b", "[$0]")))
print((string.gsub("abc", "(b)", "%1%1")))
print((string.gsub("abc", "b", "%%")))
print(pcall(string.gsub, "abc", "b", "%x"))
print((string.gsub("aaa", "a", "b", 2)))
print((string.gsub("aaa", "a", "b", 0)))
print((string.gsub("hello", "l", function(w) return w .. w end)))
print((string.gsub("hello", "[aeiou]", {a = "A", e = "E"})))
print((string.gsub("hello", "[aeiou]", function(w) return nil end)))
print((string.gsub("hello", "[aeiou]", function(w) return 42 end)))
print((string.gsub("hello", ".", function(w) return "" end)))
print((string.gsub("a b", " ", "-")))
print((string.gsub("abc", "^a", "X")))
print((string.gsub("abc", "^b", "X")))

-- gmatch
local it = string.gmatch("a1b2c3", "%a%d")
print(it(), it(), it(), it())
local acc = ""
for w in string.gmatch("one two  three", "%a+") do acc = acc .. w .. ";" end
print(acc)
local cnt = 0
for _ in string.gmatch("aaaa", "aa") do cnt = cnt + 1 end
print(cnt)

-- format
print(string.format("%d %i", 42, -7))
print(string.format("%5d|%-5d|%05d|", 42, 42, 42))
print(string.format("%x %X %o", 255, 255, 8))
print(string.format("%u", 123))
print(string.format("%c%c", 65, 66))
print(string.format("%s", "plain"), string.format("%s", 1.5), string.format("%s", nil))
print(string.format("%s", true))
print(string.format("%10s|%-10s|", "x", "x"))
print(string.format("%.3s", "abcdef"))
print(string.format("%.0f %.2f %.4f", 2.5, 3.14159, 1.0005))
print(string.format("%.0f", -0.03125))
print(string.format("%f", 0.03125))
print(string.format("%e", 3.14159), string.format("%E", 3.14159))
print(string.format("%g", 31415.9), string.format("%g", 0.0001), string.format("%g", 1234567.5))
print(string.format("%G", 0.0001))
print(string.format("%%"))
print(string.format("%q", 'a"b\nc'))
print(string.format("%q", "tab\there"))
print(string.format("no %s", "args"))
print(string.format("%s%s", "a", "b"))
print(string.format("%2s", "abcdefg"))
print(pcall(string.format, "%d", "x"))
print(pcall(string.format, "%s"))
print(pcall(string.format, "%z", 1))
print(pcall(string.format, "%"))
print(pcall(string.format, "%-+%d", 1))

-- dump / load roundtrip (binary only — this VM has no source parser)
local d = string.dump(function(q) return q + 1 end)
print(type(d), #d > 18)
local f = load(d)
print(f(41))
local d2 = string.dump(function() return "ok" end)
print((load(d2))())
print(pcall(string.dump, 1))

